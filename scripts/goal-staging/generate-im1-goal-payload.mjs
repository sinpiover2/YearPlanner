import fs from "node:fs";
import path from "node:path";
import { REVIEW_PATH, readJson, sha256, stableJson } from "./im1-goal-review-lib.mjs";

const repoRoot = path.resolve(import.meta.dirname, "../..");
const check = process.argv.includes("--check");
const review = readJson(repoRoot, REVIEW_PATH);
const previewPath = "data/parity-staging/amplify-im1-parity-preview.json";
const preview = readJson(repoRoot, previewPath);
const previewById = new Map(preview.lessonChanges.map((row) => [row.LessonID, row]));
const reviewBytes = fs.readFileSync(path.join(repoRoot, REVIEW_PATH));
const reviewSha256 = sha256(reviewBytes);
const payload = review.inventory.map((item) => {
  const row = previewById.get(item.LessonID);
  if (!row) throw new Error(`Preview is missing ${item.LessonID}.`);
  if (row.UnitID !== item.UnitID || row.LessonTitle !== item.LessonTitle || row.AfterKeyOutcome !== item.SerializedKeyOutcome || row.AfterPlannedDays !== 1) {
    throw new Error(`Preview drift for ${item.LessonID}.`);
  }
  if (!row.ChangedFields.includes("KeyOutcome") || !row.ChangedFields.includes("PlannedDays")) {
    throw new Error(`Preview is not the approved goal-and-pacing change for ${item.LessonID}.`);
  }
  return {
    CourseID: item.CourseID,
    UnitID: item.UnitID,
    LessonID: item.LessonID,
    LessonTitle: item.LessonTitle,
    KeyOutcome: item.SerializedKeyOutcome,
    PlannedDays: 1,
    NonParitySHA256: row.NonParitySHA256,
  };
});
const payloadSha256 = sha256(stableJson(payload));
const confirmationPhrase = `IMPORT-IM1-PARITY-${payloadSha256.slice(0, 16).toUpperCase()}-CONFIRMED`;
const content = `// GENERATED by scripts/goal-staging/generate-im1-goal-payload.mjs.\n// Reviewed production candidate only; loading this file performs no write.\nconst IM1_GOAL_PAYLOAD_METADATA = ${JSON.stringify({
  schemaVersion: 1,
  expectedRowCount: payload.length,
  reviewSha256,
  previewSnapshotLastUpdated: preview.sourceSnapshotLastUpdated,
  payloadSha256,
  confirmationPhrase,
}, null, 2)};\nconst IM1_GOAL_ROWS = ${JSON.stringify(payload, null, 2)};\n`;
const outputPath = path.join(repoRoot, "apps-script-planning/Im1GoalPayload.js");
if (check) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== content) throw new Error("Im1GoalPayload.js is missing or stale.");
} else {
  fs.writeFileSync(outputPath, content);
}
console.log(JSON.stringify({ check, rowCount: payload.length, payloadSha256, confirmationPhrase }, null, 2));
