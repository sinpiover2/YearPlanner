import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildPacing } from "./generate-m8-required-pacing.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const output = path.join(root, "apps-script-planning/SectionPacingPayload.js");
const rows = buildPacing().sectionPacingRows.map((row) => [
  row.PacingID,
  row.SectionID,
  row.PlannedDate,
  Number(row.Sequence),
  row.LessonID,
  false,
  row.Notes,
]);

const source = `// GENERATED by scripts/pacing-staging/generate-section-pacing-payload.mjs.\n// Local production candidate only; loading this file performs no write.\nconst SECTION_PACING_M8_ROWS = ${JSON.stringify(rows, null, 2)};\n\nif (typeof module !== "undefined" && module.exports) {\n  module.exports = { SECTION_PACING_M8_ROWS };\n}\n`;

fs.writeFileSync(output, source);
console.log(JSON.stringify({ output, rows: rows.length }));
